# ---------------------------------------------------------------- main


def main() -> int:
    ts = now_iso()
    rows = load_ledger()
    commits = git_log(6)
    changed: list[str] = []

    notes = {
        VAULT / "01 - Project" / "ORION Capabilities.md": capabilities_note(ts),
        VAULT / "01 - Project" / "ORION Screen-Vision & Actions.md": screen_note(ts),
        VAULT / "11 - Experiments" / "ORION Training Ledger.md": ledger_note(
            ts, rows, commits
        ),
    }
    for path, content in notes.items():
        if write_owned(path, content):
            changed.append(str(path.relative_to(REPO_ROOT)))

    marks = [
        (
            VAULT / "01 - Project" / "ORION.md",
            "orion-current",
            orion_block(ts, commits),
        ),
        (VAULT / "00 - Home.md", "home-training", home_block(ts)),
        (VAULT / "00 - Knowledge Graph.md", "kg-orion", kg_block(ts)),
    ]
    for path, note, block in marks:
        if upsert_marker(path, note, block):
            changed.append(str(path.relative_to(REPO_ROOT)))

    if changed:
        print("[VAULT] updated:")
        for c in changed:
            print(f"  + {c}")
    else:
        print("[VAULT] no changes (already current)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
