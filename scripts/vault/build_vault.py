#!/usr/bin/env python3
"""Regenerate the ORION Obsidian vault from live repo state.

RULE (see AGENTS.md): run this before/with every commit so the vault always
reflects reality. It is also wired as a pre-commit hook (scripts/hooks/).

What it updates:
  - vault/01 - Project/ORION Capabilities.md        (owned file)
  - vault/01 - Project/ORION Screen-Vision & Actions.md (owned file)
  - vault/11 - Experiments/ORION Training Ledger.md (owned file, from
    logs/training_runs.jsonl)
  - Marker-guarded blocks in:
      vault/01 - Project/ORION.md
      vault/00 - Home.md
      vault/00 - Knowledge Graph.md

Marker protocol: content between
    <!-- VAULT:AUTO:START note=<id> --> ... <!-- VAULT:AUTO:END -->
is regenerated on every run; anything outside markers is left untouched.

    python scripts/vault/build_vault.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
VAULT = REPO_ROOT / "vault"
LEDGER = REPO_ROOT / "logs" / "training_runs.jsonl"

START = "<!-- VAULT:AUTO:START note={note} -->"
END = "<!-- VAULT:AUTO:END -->"


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="minutes")


def git_log(n: int = 5) -> list[str]:
    try:
        out = subprocess.run(
            ["git", "log", f"-{n}", "--oneline"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=10,
        )
        return [ln for ln in out.stdout.splitlines() if ln.strip()]
    except Exception:  # noqa: BLE001 - fall back silently
        return []


def load_ledger() -> list[dict]:
    if not LEDGER.exists():
        return []
    rows = []
    for line in LEDGER.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return rows


def write_owned(path: Path, content: str) -> bool:
    """Overwrite a builder-owned note; returns True if changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    prev = path.read_text(encoding="utf-8") if path.exists() else ""
    if prev == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def upsert_marker(path: Path, note: str, block: str) -> bool:
    """Insert/replace a marker block in an existing note; returns True if changed."""
    if not path.exists():
        return False
    text = path.read_text(encoding="utf-8")
    start = START.format(note=note)
    end = END
    rendered = f"{start}\n{block}\n{end}"
    if start in text:
        pre, _rest = text.split(start, 1)
        if end in _rest:
            post = _rest.split(end, 1)[1]
            new_text = pre + rendered + post
        else:  # broken marker: append end at file tail
            new_text = pre + rendered
    else:
        # insert before the final horizontal rule (or append)
        new_text = text.rstrip()
        new_text += f"\n\n---\n\n{rendered}\n"
    if new_text == text:
        return False
    path.write_text(new_text, encoding="utf-8")
    return True


