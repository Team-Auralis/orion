def ledger_note(ts: str, rows: list[dict], commits: list[str]) -> str:
    if not rows:
        runs_table = "_(no runs recorded yet — `logs/training_runs.jsonl` empty)_"
    else:
        lines = [
            "| run_id | status | dataset | rows | epochs | start→end | Δ% | eval | dur(s) |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            rid = r.get("run_id", "?")
            status = r.get("status", "?")
            ds = Path(str(r.get("dataset_path", "?"))).name
            n = r.get("num_samples", "-")
            ep = r.get("epochs", "-")
            sl = r.get("starting_loss")
            el = r.get("ending_loss")
            red = r.get("loss_reduction_pct")
            ev = r.get("eval_loss")
            dur = r.get("duration_seconds")
            fmt = lambda v: f"{v:.4f}" if isinstance(v, (int, float)) else "-"
            lines.append(
                f"| `{rid}` | {status} | {ds} | {n} | {ep} | "
                f"{fmt(sl)} → {fmt(el)} | {red if isinstance(red, (int, float)) else '-'} | "
                f"{fmt(ev)} | {dur if isinstance(dur, (int, float)) else '-'} |"
            )
        runs_table = "\n".join(lines)

    commit_lines = "\n".join(f"- `{c}`" for c in commits) or "- _(git unavailable)_"

    return f"""# ORION Training Ledger

#experiment #governance

> *Auto-generated by `scripts/vault/build_vault.py` from
> `logs/training_runs.jsonl` — edit the builder, not this file.*
> *Last sync: {ts}*

Every training run ORION logged, with honest metrics. Failures are recorded
with `error_message`. Run → capability links: [[ORION Capabilities]] and
[[ORION Screen-Vision & Actions]].

## Runs

{runs_table}

## Honest warnings

- Loss gains are training-metric gains; generation quality remains
  filler-grade at the 100M scale (**UNPROVEN**).
- Vision-action runs converge on loss yet score **0/10 held-out** — see
  [[ORION Screen-Vision & Actions]].

## Recent commits (context)

{commit_lines}

## Related

- [[ORION]]
- [[ORION Capabilities]]
- [[00 - Knowledge Graph]]
- [[00 - Home]]
"""


